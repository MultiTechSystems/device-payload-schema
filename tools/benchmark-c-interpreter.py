#!/usr/bin/env python3
"""Benchmark the C interpreter against the Python reference on one corpus schema.

`docs/SPEC-IMPLEMENTATION-STATUS.md` carried a C row whose numbers no committed thing
produced. `src/benchmark.cpp` looks like the source but is not: it times a small
interpreter it defines inline plus a generated codec, and never includes
`schema_interpreter.h`. So the figures could not be checked, and the prose beside them
went stale without anything noticing - it justified a simplified benchmark frame by
saying the C interpreter "has no `flagged`", which CR-2026-034 made untrue.

This regenerates both rows from source. The point of interest is that **the C schema is
built from the same YAML the Python reference reads**, by reusing
`c-corpus-harness.py`'s `schema_source()`. A hand-transcribed C copy of the schema is
the obvious way to write this and the wrong one: it can drift from the YAML silently,
and then the two rows are no longer measuring the same work.

What is timed is `schema_decode` alone, with the schema built once outside the loop, so
the rows mean "decode a payload with a schema already in memory". Neither figure
includes YAML parsing or schema construction.

The default frame is `dl-lid`, the richest `flagged` schema the struct API can build:
three plain fields and a two-group `flagged` covering twelve more. DL-5TM, which the
other rows in that document use, remains out of reach - it needs `polynomial` and
`transform`, and the C interpreter has neither.
"""

import argparse
import importlib.util
import json
import shutil
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
HARNESS = REPO_ROOT / "tools" / "c-corpus-harness.py"
DEFAULT_SCHEMA = REPO_ROOT / "schemas" / "devices" / "decentlab" / "dl-lid.yaml"

sys.path.insert(0, str(REPO_ROOT / "tools"))


def load_harness():
    """The corpus harness, imported for its schema builder rather than re-implemented."""
    spec = importlib.util.spec_from_file_location("c_corpus_harness", HARNESS)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


PROGRAM = '''/* Generated by tools/benchmark-c-interpreter.py - do not commit.
 *
 * Times schema_decode() with the schema built once, outside the loop.
 */
#include "schema_interpreter.h"
#include <stdio.h>
#include <string.h>
#include <time.h>

%(build)s

/* The decoded values are accumulated into this and printed. Without a consumer the
 * whole loop is dead code and -O2 is entitled to delete it, which would report an
 * arbitrarily large ops/s. */
static volatile long long sink = 0;

static double seconds_for(int iterations, const uint8_t* p, int len, schema_t* s) {
    decode_result_t r;
    struct timespec a, b;
    clock_gettime(CLOCK_MONOTONIC, &a);
    for (int i = 0; i < iterations; i++) {
        if (schema_decode(s, p, len, &r) != SCHEMA_OK) return -1.0;
        sink += r.field_count;
    }
    clock_gettime(CLOCK_MONOTONIC, &b);
    return (double)(b.tv_sec - a.tv_sec) + (double)(b.tv_nsec - a.tv_nsec) / 1e9;
}

int main(void) {
    static const uint8_t payload[] = {%(payload)s};
    const int len = %(len)d;
    schema_t s;
    build_0(&s);

    /* Prove it decodes before timing it. A benchmark of a failing decode is a
     * benchmark of the error path. */
    decode_result_t once;
    int rc = schema_decode(&s, payload, len, &once);
    if (rc != SCHEMA_OK) { printf("ERR\\t%%d\\t%%s\\n", rc, once.error_msg); return 1; }
    printf("FIELDS\\t%%d\\n", once.field_count);

    seconds_for(%(warmup)d, payload, len, &s);   /* warm caches, ignore */

    for (int round = 0; round < %(rounds)d; round++) {
        double elapsed = seconds_for(%(iterations)d, payload, len, &s);
        if (elapsed < 0) { printf("ERR\\tdecode failed mid-loop\\n"); return 1; }
        printf("ROUND\\t%%.9f\\n", elapsed);
    }
    printf("SINK\\t%%lld\\n", sink);
    return 0;
}
'''


def pick_vector(schema, wanted):
    """The vector to time: the named one, else the longest payload.

    The longest exercises the most fields - for a `flagged` schema that means the most
    groups set, which is the case worth timing.
    """
    vectors = schema.get("test_vectors") or []
    if not vectors:
        raise SystemExit("schema has no test_vectors to benchmark")
    if wanted:
        for vector in vectors:
            if vector.get("name") == wanted:
                return vector
        raise SystemExit(f"no vector named {wanted!r}")
    return max(vectors, key=lambda v: len(str(v.get("payload", ""))))


def build_c(schema, vector, args, harness):
    source, reason = harness.schema_source(0, schema)
    if source is None:
        raise SystemExit(f"the struct API cannot build this schema: {reason}")
    payload = bytes.fromhex(str(vector["payload"]).replace(" ", ""))
    return PROGRAM % {
        "build": "\n".join(source),
        "payload": ", ".join(f"0x{b:02x}" for b in payload) or "0",
        "len": len(payload),
        "warmup": max(1000, args.iterations // 10),
        "iterations": args.iterations,
        "rounds": args.rounds,
    }, payload


def run_c(program, args):
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        src, binary = tmp / "bench.c", tmp / "bench"
        src.write_text(program)
        compile_cmd = [args.cc, "-O2", "-Os", "-I", str(REPO_ROOT / "include"),
                       str(src), "-o", str(binary)]
        done = subprocess.run(compile_cmd, capture_output=True, text=True)
        if done.returncode != 0:
            raise SystemExit(f"compile failed:\n{done.stderr[-3000:]}")
        run = subprocess.run([str(binary)], capture_output=True, text=True)
        if run.returncode != 0:
            raise SystemExit(f"benchmark failed:\n{run.stdout}\n{run.stderr}")

        # Size is reported stripped, which is what an embedded target would ship.
        size = None
        if shutil.which("strip"):
            stripped = tmp / "bench.stripped"
            shutil.copy(binary, stripped)
            if subprocess.run(["strip", str(stripped)],
                              capture_output=True).returncode == 0:
                size = stripped.stat().st_size

    rounds, fields = [], None
    for line in run.stdout.splitlines():
        kind, _, rest = line.partition("\t")
        if kind == "ROUND":
            rounds.append(float(rest))
        elif kind == "FIELDS":
            fields = int(rest)
        elif kind == "ERR":
            raise SystemExit(f"C decode failed: {rest}")
    if not rounds:
        raise SystemExit(f"no timing rounds in output:\n{run.stdout}")
    return rounds, fields, size


def run_python(schema, payload, args):
    from schema_interpreter import SchemaInterpreter

    interpreter = SchemaInterpreter(schema)          # built once, as on the C side
    result = interpreter.decode(payload)
    if getattr(result, "errors", None):
        raise SystemExit(f"python decode failed: {result.errors}")

    rounds = []
    for _ in range(args.rounds):
        # A fresh interpreter per round would time construction too; the C side builds
        # once, so this does as well.
        start = time.perf_counter()
        for _ in range(args.python_iterations):
            interpreter.decode(payload)
        rounds.append(time.perf_counter() - start)
    return rounds, len(result.data)


def best(rounds, iterations):
    """The fastest round, not the mean.

    A benchmark's slow rounds are the ones the OS interfered with; the fastest is the
    closest to the work itself. The spread is reported so a noisy machine is visible
    rather than averaged into the number.
    """
    per_op = [r / iterations for r in rounds]
    fastest = min(per_op)
    return {
        "ops_per_sec": 1.0 / fastest,
        "ns_per_op": fastest * 1e9,
        "rounds": len(rounds),
        "spread_pct": ((max(per_op) - fastest) / fastest * 100.0) if fastest else 0.0,
        "median_ns_per_op": statistics.median(per_op) * 1e9,
    }


def human(ops):
    if ops >= 1e6:
        return f"{ops / 1e6:.1f}M ops/s"
    if ops >= 1e3:
        return f"{ops / 1e3:.0f}K ops/s"
    return f"{ops:.0f} ops/s"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    parser.add_argument("--vector", help="test vector name (default: longest payload)")
    parser.add_argument("--iterations", type=int, default=2_000_000,
                        help="C decodes per round (default 2000000)")
    parser.add_argument("--python-iterations", type=int, default=20_000,
                        help="Python decodes per round (default 20000)")
    parser.add_argument("--rounds", type=int, default=5)
    parser.add_argument("--cc", default="cc")
    parser.add_argument("--json", metavar="PATH")
    args = parser.parse_args()

    schema = yaml.safe_load(args.schema.read_text())
    vector = pick_vector(schema, args.vector)
    harness = load_harness()

    program, payload = build_c(schema, vector, args, harness)
    c_rounds, c_fields, size = run_c(program, args)
    py_rounds, py_fields = run_python(schema, payload, args)

    c = best(c_rounds, args.iterations)
    py = best(py_rounds, args.python_iterations)
    report = {
        "schema": str(args.schema.relative_to(REPO_ROOT)),
        "schema_name": schema.get("name"),
        "vector": vector.get("name"),
        "payload_bytes": len(payload),
        "c_fields_decoded": c_fields,
        "python_fields_decoded": py_fields,
        "c": c, "python": py,
        "ratio": c["ops_per_sec"] / py["ops_per_sec"] if py["ops_per_sec"] else None,
        "stripped_bytes": size,
        "flagged": any(isinstance(f, dict) and "flagged" in f
                       for f in schema.get("fields", [])),
    }

    print(f"{report['schema']}  vector={report['vector']}  "
          f"{report['payload_bytes']} B  flagged={report['flagged']}")
    print(f"  fields decoded: C {c_fields}, Python {py_fields}")
    print(f"  C interpreter  {human(c['ops_per_sec']):>12}  "
          f"{c['ns_per_op']:8.1f} ns/op  (spread {c['spread_pct']:.1f}%)")
    print(f"  Python         {human(py['ops_per_sec']):>12}  "
          f"{py['ns_per_op']:8.1f} ns/op  (spread {py['spread_pct']:.1f}%)")
    print(f"  ratio          {report['ratio']:.0f}x")
    if size:
        print(f"  stripped       {size / 1024:.1f} KB (interpreter + schema + harness)")

    if args.json:
        Path(args.json).write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()

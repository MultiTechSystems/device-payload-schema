#!/usr/bin/env python3
"""CI gate: no schema's mutation score may fall.

`tools/schema-mutation.py` mutates each corpus schema one small change at a time and
asks whether any of its vectors notices; its score is killed / (killed + survived). A
high `score_schema.py` tier says a schema agrees with its own vectors, and this says how
much of the schema those vectors actually pin. The harness is deterministic (same
schema, same vectors, same mutants), so this gate compares exactly.

Ratchet against the committed `tools/mutation-baseline.json`, in the same spirit as
`score-baseline.json` and the language floors. Fails when:

  * a baselined schema's score is below its baseline (a vector removed, or a schema
    change no vector checks);
  * a baselined schema no longer has decode vectors, or disappeared (refresh the
    baseline deliberately if that was intended);
  * a schema absent from the baseline scores below --min-score (default 0.80). A new
    schema should arrive with vectors that pin it. 0.80 is met by 142 of the 150
    scored schemas in the corpus the baseline was built from (median 0.98), so it
    asks for coverage typical of the corpus without demanding perfection on day one;
  * a schema has more vectors failing on the UNMUTATED schema than its baseline (a
    new schema: any) - a failing vector kills nothing, so its score would flatter it;
  * the harness reports an error for a schema.

  * a baselined schema's killed count falls by more than its generated mutant count
    does. Removing vectors can RAISE the score, because a mutant only they reached
    becomes `unreached` and leaves the denominator; the killed ratchet catches that.
    A fall matched by the schema offering fewer mutants (a field removed) is reported,
    not failed.

Improvements are reported and locked in by --update.

    python3 tools/mutation-gate.py
    python3 tools/mutation-gate.py --changed-since origin/master   # + survivors
    python3 tools/mutation-gate.py --changed-since origin/master --only-changed
    python3 tools/mutation-gate.py --shard 2/4 --parts-out build/mutation/2.json
    python3 tools/mutation-gate.py --parts-in build/mutation
    python3 tools/mutation-gate.py --update

--only-changed (with --changed-since) scores only the corpus schemas that differ from
the merge base with that ref - what a pull request adds or modifies - and judges them by
the full sweep's rules: a baselined schema against its entry, a new one against the
new-schema floor, a deleted or vector-less baselined one as missing. It runs the full
sweep instead when the diff touches anything that can move every schema's score: the
mutation harness, this gate, the baseline, requirements.txt, or a tools/ module the
harness loads (the reference interpreter and what it imports). See full_sweep_reasons().

One schema dominates the sweep (volley-boast/vobo: about 25,000 mutants, each replayed
against 436 vectors), so the work is planned in units: a schema, or a contiguous part of
a heavy schema's mutant list (plan_parts). Parts are merged back into exactly the report
an unsplit run gives (schema-mutation.py merge_parts), so splitting changes no score.

--shard I/N --parts-out FILE runs the I-th of N disjoint slices of those units, balanced
by each unit's estimated cost from the baseline, and writes the reports unjudged. Every
shard plans the same units from the same tree. --parts-in DIR then reassembles every
shard's reports, checks that each schema in scope is there whole, and judges them
exactly as a single run would. --update always scores the whole corpus in one run.

`schemas/devices/_library-composed/` is excluded by default. Those files are generated by
`tools/compose_library_vectors.py`, one standalone schema per library vector, so their
score measures one example of a definition catalogue rather than a device, and a PR
author cannot raise it by editing the file - it is regenerated wholesale. Its vectors
come from `schemas/library/`. Pass --include-library-composed to score them anyway.
"""

import argparse
import importlib.util
import json
import math
import multiprocessing
import os
import subprocess
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Set, Tuple

REPO_ROOT = Path(__file__).resolve().parent.parent
TOOLS = REPO_ROOT / "tools"
CORPUS = REPO_ROOT / "schemas" / "devices"
BASELINE_FILE = TOOLS / "mutation-baseline.json"

DEFAULT_MIN_SCORE = 0.80
#: Splitting a heavy schema's mutants (plan_parts): jobs aimed at per worker, the
#: most parts for one schema, and the least estimated work worth a part of its own.
PARTS_PER_WORKER = 4
MAX_PARTS = 64
MIN_PART_WEIGHT = 200000.0
#: Changing any of these can move every schema's score, so --only-changed runs the
#: full sweep when one is in the diff. Repository-relative. The tools/ modules the
#: harness actually loads are added at run time (harness_sources), so a new import
#: of the interpreter's is covered without editing this list.
FULL_SWEEP_FILES = (
    "tools/schema-mutation.py",
    "tools/mutation-gate.py",
    "tools/mutation-baseline.json",
    "tools/schema_interpreter.py",
    "requirements.txt",
)
LIBRARY_COMPOSED = "_library-composed"
#: The harness rounds scores to 4 places; this only absorbs float representation.
EPSILON = 1e-9


def load_harness():
    path = TOOLS / "schema-mutation.py"
    spec = importlib.util.spec_from_file_location("schema_mutation", str(path))
    module = importlib.util.module_from_spec(spec)
    sys.modules["schema_mutation"] = module
    spec.loader.exec_module(module)
    return module


# --------------------------------------------------------------------------- rules


def compare(
    baseline: Dict[str, Dict[str, Any]],
    current: Dict[str, Dict[str, Any]],
    min_score: float = DEFAULT_MIN_SCORE,
) -> Dict[str, List[str]]:
    """Apply the ratchet. Maps are {schema_key: {score, killed, survived, ...}}.

    Returns lists of `regressions`, `improvements` and `notes`. Pure: no I/O.
    """
    regressions = []  # type: List[str]
    improvements = []  # type: List[str]
    notes = []  # type: List[str]

    for key in sorted(set(baseline) - set(current)):
        regressions.append(
            "%s: in the baseline but not scored now - it lost its decode vectors or "
            "was removed; refresh the baseline with --update if deliberate" % key
        )
    for key in sorted(current):
        now = current[key]
        if now.get("error"):
            regressions.append("%s: harness error: %s" % (key, now["error"]))
            continue
        score = now.get("score")
        was = baseline.get(key)
        if was is None:
            if now.get("failing_original", 0):
                regressions.append(
                    "%s: new schema has %d vector(s) failing on the unmutated schema"
                    % (key, now["failing_original"])
                )
            if score is None:
                notes.append("%s: new schema, no scorable mutants" % key)
            elif score + EPSILON < min_score:
                regressions.append(
                    "%s: new schema scores %s, below the %s floor for new schemas "
                    "(killed %d, survived %d) - add vectors that pin the survivors"
                    % (
                        key,
                        _pct(score),
                        _pct(min_score),
                        now["killed"],
                        now["survived"],
                    )
                )
            else:
                improvements.append(
                    "%s: new schema, %s (killed %d)" % (key, _pct(score), now["killed"])
                )
            continue
        old = was.get("score")
        if old is not None and score is None:
            regressions.append(
                "%s: scored %s in the baseline, no scorable mutants now"
                % (key, _pct(old))
            )
            continue
        if old is None or score is None:
            if old is None and score is not None:
                improvements.append("%s: now scored, %s" % (key, _pct(score)))
            continue
        lost = was["killed"] - now["killed"]
        shrink = was.get("generated", 0) - now.get("generated", 0)
        # Fewer vectors can RAISE the score: a mutant only they reached becomes
        # `unreached`, which the score leaves out. So killed is ratcheted too, and a
        # fall is excused only by the schema itself offering fewer mutants.
        coverage_lost = lost > 0 and lost > max(shrink, 0)
        if score + EPSILON < old:
            regressions.append(
                "%s: mutation score fell %s -> %s (killed %d -> %d, survived %d -> %d)"
                % (
                    key,
                    _pct(old),
                    _pct(score),
                    was["killed"],
                    now["killed"],
                    was["survived"],
                    now["survived"],
                )
            )
        elif coverage_lost:
            regressions.append(
                "%s: killed fell %d -> %d while the schema's mutants fell only "
                "%d -> %d - vectors that pinned those sites are gone (score %s -> %s)"
                % (
                    key,
                    was["killed"],
                    now["killed"],
                    was.get("generated", 0),
                    now.get("generated", 0),
                    _pct(old),
                    _pct(score),
                )
            )
        elif score > old + EPSILON:
            improvements.append(
                "%s: mutation score rose %s -> %s" % (key, _pct(old), _pct(score))
            )
        elif lost > 0:
            notes.append(
                "%s: killed fell %d -> %d with the schema's mutants %d -> %d"
                % (
                    key,
                    was["killed"],
                    now["killed"],
                    was.get("generated", 0),
                    now.get("generated", 0),
                )
            )
        elif lost < 0:
            improvements.append(
                "%s: killed rose %d -> %d" % (key, was["killed"], now["killed"])
            )
        failing, was_failing = now.get("failing_original", 0), was.get(
            "failing_original", 0
        )
        if failing > was_failing:
            regressions.append(
                "%s: %d vector(s) now fail on the unmutated schema (baseline %d); a "
                "failing vector kills nothing, so the score above overstates it"
                % (key, failing, was_failing)
            )
    return {"regressions": regressions, "improvements": improvements, "notes": notes}


def _pct(value):
    return "n/a" if value is None else "%.1f%%" % (value * 100)


def distribution(entries: Dict[str, Dict[str, Any]]) -> Dict[str, int]:
    bands = [
        ("100%", 1.0, 1.01),
        ("95-99%", 0.95, 1.0),
        ("90-94%", 0.90, 0.95),
        ("80-89%", 0.80, 0.90),
        ("70-79%", 0.70, 0.80),
        ("<70%", -1.0, 0.70),
    ]
    out = {label: 0 for label, _lo, _hi in bands}
    out["unscored"] = 0
    for entry in entries.values():
        score = entry.get("score")
        if score is None:
            out["unscored"] += 1
            continue
        for label, lo, hi in bands:
            if lo <= score < hi:
                out[label] += 1
                break
    return out


# --------------------------------------------------------------------------- running


def _key(path: Path, schemas_dir: Path) -> str:
    return path.resolve().relative_to(schemas_dir.resolve()).as_posix()


def select_files(harness, schemas_dir: Path, include_library: bool) -> List[Path]:
    files = harness.schema_files([str(schemas_dir)])
    if not include_library:
        files = [
            f
            for f in files
            if _key(f, schemas_dir).split("/", 1)[0] != LIBRARY_COMPOSED
        ]
    return files


def plan_parts(
    weights: Dict[str, float], keys: Iterable[str], workers: int
) -> Dict[str, int]:
    """How many parts to split each schema's mutants into. Pure.

    One schema can dominate the sweep - volley-boast/vobo carries about 97% of the
    corpus's mutant-vector work, so unsplit it held one worker for the whole run while
    the rest sat idle. A schema heavier than a fair share of the work is split into
    contiguous parts of its mutant list (schema-mutation.py merge_parts() reassembles
    them exactly), aiming at PARTS_PER_WORKER jobs per worker; a schema lighter than
    MIN_PART_WEIGHT is never split, since each part repeats the schema's setup.
    """
    keys = list(keys)
    total = sum(weights.get(k, 0.0) for k in keys)
    if workers <= 1 or total <= 0:
        return {k: 1 for k in keys}
    target = max(total / (workers * PARTS_PER_WORKER), MIN_PART_WEIGHT)
    return {
        k: max(1, min(MAX_PARTS, int(math.ceil(weights.get(k, 0.0) / target))))
        for k in keys
    }


def plan_jobs(
    files: List[Path],
    schemas_dir: Path,
    weights: Dict[str, float],
    workers: int,
) -> List[Tuple[str, tuple, float]]:
    """[(unit, harness job, estimated cost)] for `files`, heaviest first. Pure.

    A unit is a schema key, or `key#i/n` for part i of a schema split n ways by
    plan_parts(). Deterministic, so every shard of a matrix plans the same units.
    """
    keys = {str(f): _key(f, schemas_dir) for f in files}
    parts = plan_parts(weights, keys.values(), workers)
    known = sorted(w for w in weights.values() if w > 0)
    default = known[len(known) // 2] if known else 0.0
    out = []  # type: List[Tuple[str, tuple, float]]
    for f in files:
        key = keys[str(f)]
        count = parts[key]
        cost = (weights.get(key) or default) / count
        if count == 1:
            out.append((key, (str(f), None, 5.0), cost))
        else:
            out.extend(
                ("%s#%d/%d" % (key, i, count), (str(f), None, 5.0, (i, count)), cost)
                for i in range(count)
            )
    out.sort(key=lambda u: (-u[2], -os.path.getsize(u[1][0]), u[0]))
    return out


def execute(jobs: List[tuple], workers: int, harness) -> List[Dict[str, Any]]:
    """Run harness jobs, in parallel where the platform allows; reports in job order."""
    # fork, so the workers inherit the harness module loaded above; a platform
    # without it runs serially rather than failing to unpickle the job function.
    fork = "fork" in multiprocessing.get_all_start_methods()
    if workers > 1 and len(jobs) > 1 and fork:
        context = multiprocessing.get_context("fork")
        with ProcessPoolExecutor(max_workers=workers, mp_context=context) as pool:
            return list(pool.map(harness.mutate_file, jobs))
    return [harness.mutate_file(j) for j in jobs]


def assemble(
    units: Iterable[Tuple[str, Dict[str, Any]]], harness
) -> Dict[str, Dict[str, Any]]:
    """{schema_key: report} from (unit, report) pairs, merging a split schema's parts.

    A unit seen twice, or a split schema missing a part, is an error rather than a
    report: either would judge a schema on work that does not match one whole run.
    """
    grouped = {}  # type: Dict[str, Dict[str, Dict[str, Any]]]
    for unit, report in units:
        key = unit.split("#", 1)[0]
        pieces = grouped.setdefault(key, {})
        if unit in pieces:
            raise ValueError("unit %s reported twice" % unit)
        pieces[unit] = report
    out = {}
    for key, pieces in grouped.items():
        if list(pieces) == [key]:
            out[key] = pieces[key]
        elif key in pieces:
            raise ValueError("%s reported both whole and in parts" % key)
        else:
            out[key] = harness.merge_parts(list(pieces.values()))
    return out


def run_harness(
    schemas_dir: Path,
    include_library: bool = False,
    workers: int = 1,
    only: Optional[Set[str]] = None,
    harness=None,
    weights: Optional[Dict[str, float]] = None,
) -> Dict[str, Dict[str, Any]]:
    """{schema_key: full harness report} for every scorable schema under the tree.

    With `only`, just the scorable schemas whose keys it holds. `weights` (cost
    estimates, see baseline_weights) order the work and split the heaviest schemas.
    """
    harness = harness or load_harness()
    files = scoped_files(harness, schemas_dir, include_library, only)
    planned = plan_jobs(files, schemas_dir, weights or {}, workers)
    reports = execute([job for _unit, job, _cost in planned], workers, harness)
    return assemble(zip([unit for unit, _job, _cost in planned], reports), harness)


def scoped_files(
    harness, schemas_dir: Path, include_library: bool, only: Optional[Set[str]]
) -> List[Path]:
    files = select_files(harness, schemas_dir, include_library)
    if only is not None:
        files = [f for f in files if _key(f, schemas_dir) in only]
    return files


def run_shard(
    schemas_dir: Path,
    include_library: bool,
    workers: int,
    only: Optional[Set[str]],
    harness,
    weights: Dict[str, float],
    index: int,
    count: int,
) -> Dict[str, Any]:
    """Run slice `index` of `count` of the planned units and return them, unjudged.

    The units are planned for `count * workers` processes, so a schema too heavy for
    one runner is split across the matrix; --parts-in reassembles and judges them.
    """
    files = scoped_files(harness, schemas_dir, include_library, only)
    planned = plan_jobs(files, schemas_dir, weights, workers * count)
    mine = shard_of(
        [u for u, _j, _c in planned], {u: c for u, _j, c in planned}, index, count
    )
    chosen = [(u, j) for u, j, _c in planned if u in mine]
    reports = execute([j for _u, j in chosen], workers, harness)
    return {
        "shard": [index, count],
        "units": {u: r for (u, _j), r in zip(chosen, reports)},
    }


def load_shards(directory: Path, harness) -> Dict[str, Dict[str, Any]]:
    """Every shard's units under `directory` (searched recursively), assembled."""
    units = []  # type: List[Tuple[str, Dict[str, Any]]]
    for path in sorted(directory.rglob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        units.extend(data.get("units", {}).items())
    return assemble(units, harness)


def slim(report: Dict[str, Any]) -> Dict[str, Any]:
    if "error" in report:
        return {"error": report["error"]}
    return {
        "score": report["score"],
        "killed": report["killed"],
        "survived": report["survived"],
        "unreached": report["unreached"],
        "generated": report["generated"],
        "vectors": report["vectors"],
        "provenance": report["provenance"],
        "failing_original": len(report.get("vectors_failing_original") or []),
    }


def build_baseline(current, min_score, include_library) -> Dict[str, Any]:
    entries = {k: slim(v) for k, v in sorted(current.items())}
    return {
        "about": (
            "Committed ratchet for tools/mutation-gate.py: each schema's "
            "tools/schema-mutation.py score may not fall. Regenerate only "
            "deliberately (--update) and say why in the commit message."
        ),
        "min_score_new": min_score,
        "include_library_composed": include_library,
        "distribution": distribution(entries),
        "schemas": entries,
    }


def _git(*args: str) -> str:
    out = subprocess.run(
        ["git"] + list(args),
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        timeout=60,
    )
    if out.returncode != 0:
        raise SystemExit("git failed: git %s\n%s" % (" ".join(args), out.stderr))
    return out.stdout


def changed_paths(ref: str) -> List[str]:
    """Repository paths that differ from the merge base with `ref`.

    Committed, staged, unstaged and untracked changes all count, so a local run sees
    what a pull request would. Diffing from the merge base rather than `ref` keeps
    commits that landed on `ref` after the branch was cut out of this branch's
    changes; in CI the checkout is the PR's merge commit, whose merge base with its
    base branch is that branch's head, so the diff is exactly the PR's.
    """
    merge_base = _git("merge-base", ref, "HEAD").strip()
    names = set(_git("diff", "--name-only", merge_base, "--").splitlines())
    names.update(_git("ls-files", "--others", "--exclude-standard").splitlines())
    return sorted(n.strip() for n in names if n.strip())


def schema_keys(paths: Iterable[str], schemas_dir: Path) -> List[str]:
    """The corpus keys among repository-relative `paths`, deleted files included."""
    keys = set()
    root = schemas_dir.resolve()
    for name in paths:
        path = (REPO_ROOT / name).resolve()
        if path.suffix == ".yaml":
            try:
                keys.add(path.relative_to(root).as_posix())
            except ValueError:
                continue
    return sorted(keys)


def changed_schemas(ref: str, schemas_dir: Path) -> List[str]:
    """Schema keys changed since the merge base with `ref`, working tree included."""
    return schema_keys(changed_paths(ref), schemas_dir)


def harness_sources() -> List[str]:
    """Repository paths of the tools/ modules loaded once the harness is imported.

    The harness imports the reference interpreter, which imports its helpers; a change
    to any of them can change any schema's decode, and with it any score.
    """
    tools = TOOLS.resolve()
    repo = REPO_ROOT.resolve()
    out = set()
    for module in list(sys.modules.values()):
        name = getattr(module, "__file__", None)
        if not name:
            continue
        path = Path(name).resolve()
        if path.parent == tools:
            out.add(path.relative_to(repo).as_posix())
    return sorted(out)


def full_sweep_reasons(changed: Iterable[str], sources: Iterable[str]) -> List[str]:
    """The changed paths that oblige --only-changed to score the whole corpus. Pure."""
    triggers = set(FULL_SWEEP_FILES) | set(sources)
    return sorted(p for p in set(changed) if p in triggers)


def baseline_weights(entries: Dict[str, Dict[str, Any]]) -> Dict[str, float]:
    """A cost estimate per schema: mutants generated times vectors replayed for each."""
    out = {}
    for key, entry in entries.items():
        generated = entry.get("generated") or 0
        vectors = entry.get("vectors") or 1
        out[key] = float(generated * max(vectors, 1))
    return out


def shard_of(
    keys: Iterable[str], weights: Dict[str, float], index: int, count: int
) -> Set[str]:
    """The keys in slice `index` (1-based) of `count`. Pure and deterministic.

    Longest-processing-time greedy: heaviest first, each onto the lightest shard so
    far, ties broken by key and by shard number. A key with no weight (a new schema)
    costs the median known weight, so a batch of new schemas spreads out.
    """
    if count < 1 or not 1 <= index <= count:
        raise ValueError("shard %d/%d is out of range" % (index, count))
    keys = sorted(set(keys))
    known = sorted(weights[k] for k in keys if weights.get(k, 0) > 0)
    default = known[len(known) // 2] if known else 1.0
    cost = {k: (weights.get(k) or default) for k in keys}
    loads = [0.0] * count
    members = [set() for _ in range(count)]  # type: List[Set[str]]
    for key in sorted(keys, key=lambda k: (-cost[k], k)):
        slot = min(range(count), key=lambda i: (loads[i], i))
        loads[slot] += cost[key]
        members[slot].add(key)
    return members[index - 1]


def parse_shard(text: str) -> Tuple[int, int]:
    try:
        index, count = (int(part) for part in text.split("/"))
    except ValueError:
        raise argparse.ArgumentTypeError("--shard takes I/N, e.g. 2/4")
    if count < 1 or not 1 <= index <= count:
        raise argparse.ArgumentTypeError("--shard %s is out of range" % text)
    return index, count


def print_survivors(key: str, report: Dict[str, Any]):
    survivors = report.get("survivors") or []
    print(
        "\n%s: %s, %d surviving mutant(s)"
        % (key, _pct(report.get("score")), len(survivors))
    )
    for s in survivors:
        extra = ""
        if s.get("changed_keys"):
            extra = "  (changed: %s)" % ", ".join(s["changed_keys"])
        print(
            "    %-10s %-40s %s [%s]%s"
            % (s["operator"], s["field"], s["detail"], s.get("kind", ""), extra)
        )


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--schemas-dir", default=str(CORPUS))
    parser.add_argument("--baseline", default=str(BASELINE_FILE))
    parser.add_argument(
        "--min-score",
        type=float,
        default=None,
        help="floor for schemas not in the baseline (default: the baseline's "
        "min_score_new, else %.2f)" % DEFAULT_MIN_SCORE,
    )
    parser.add_argument("--include-library-composed", action="store_true")
    parser.add_argument("--workers", type=int, default=os.cpu_count() or 1)
    parser.add_argument(
        "--changed-since",
        metavar="REF",
        help="list surviving mutants of every schema changed since this git ref",
    )
    parser.add_argument(
        "--only-changed",
        action="store_true",
        help="with --changed-since, score only the changed schemas, unless the diff "
        "touches the harness, this gate, the baseline or the interpreter",
    )
    parser.add_argument(
        "--shard",
        type=parse_shard,
        metavar="I/N",
        help="run only slice I of N of the work and write it to --parts-out, "
        "unjudged; a heavy schema's mutants are split across the slices",
    )
    parser.add_argument(
        "--parts-out",
        metavar="FILE",
        help="with --shard: where to write this slice's harness reports",
    )
    parser.add_argument(
        "--parts-in",
        metavar="DIR",
        help="judge the reports every --shard wrote under DIR instead of running "
        "the harness; every schema in scope must be there, every part of it",
    )
    parser.add_argument(
        "--update", action="store_true", help="rewrite the baseline from this run"
    )
    args = parser.parse_args(argv)
    if args.only_changed and not args.changed_since:
        parser.error("--only-changed needs --changed-since REF")
    if args.update and (args.only_changed or args.shard or args.parts_in):
        parser.error(
            "--update scores the whole corpus in one run; drop "
            "--only-changed/--shard/--parts-in"
        )
    if bool(args.shard) != bool(args.parts_out):
        parser.error("--shard and --parts-out go together")
    if args.shard and args.parts_in:
        parser.error("--shard runs a slice and --parts-in judges them all; pick one")

    schemas_dir = Path(args.schemas_dir).resolve()
    baseline_path = Path(args.baseline)
    baseline = (
        json.loads(baseline_path.read_text(encoding="utf-8"))
        if baseline_path.exists()
        else None
    )
    min_score = args.min_score
    if min_score is None:
        min_score = (baseline or {}).get("min_score_new", DEFAULT_MIN_SCORE)

    harness = load_harness()
    # None judges the whole corpus, exactly as before these options existed.
    scope = None  # type: Optional[Set[str]]
    if args.only_changed:
        paths = changed_paths(args.changed_since)
        reasons = full_sweep_reasons(paths, harness_sources())
        if reasons:
            print(
                "--only-changed: running the full sweep, because the diff since %s "
                "touches %s" % (args.changed_since, ", ".join(reasons))
            )
        else:
            scope = set(schema_keys(paths, schemas_dir))
            if not args.include_library_composed:
                scope = {k for k in scope if k.split("/", 1)[0] != LIBRARY_COMPOSED}
            print(
                "--only-changed: %d corpus schema(s) changed since %s%s"
                % (
                    len(scope),
                    args.changed_since,
                    "".join("\n    " + k for k in sorted(scope)),
                )
            )
    weights = baseline_weights((baseline or {}).get("schemas", {}))
    started = time.time()
    if args.shard:
        index, count = args.shard
        data = run_shard(
            schemas_dir,
            args.include_library_composed,
            args.workers,
            scope,
            harness,
            weights,
            index,
            count,
        )
        out = Path(args.parts_out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(data) + "\n", encoding="utf-8")
        print(
            "--shard %d/%d: %d unit(s) in %.1fs, written to %s; judge every shard "
            "with --parts-in"
            % (index, count, len(data["units"]), time.time() - started, out)
        )
        return 0
    if args.parts_in:
        try:
            current = load_shards(Path(args.parts_in), harness)
        except ValueError as exc:
            print("FAIL: the shard reports under %s: %s" % (args.parts_in, exc))
            return 1
        files = scoped_files(harness, schemas_dir, args.include_library_composed, scope)
        expected = {_key(f, schemas_dir) for f in files}
        missing = sorted(expected - set(current))
        extra = sorted(set(current) - expected)
        if missing or extra:
            print(
                "FAIL: the shard reports under %s do not match this tree: missing %s, "
                "unexpected %s" % (args.parts_in, missing or "none", extra or "none")
            )
            return 1
    else:
        current = run_harness(
            schemas_dir,
            args.include_library_composed,
            args.workers,
            only=scope,
            harness=harness,
            weights=weights,
        )
    elapsed = time.time() - started
    slimmed = {k: slim(v) for k, v in current.items()}
    dist = distribution(slimmed)
    print(
        "%d schemas scored in %.1fs: %s"
        % (len(current), elapsed, ", ".join("%s %d" % kv for kv in dist.items()))
    )

    if args.changed_since:
        keys = changed_schemas(args.changed_since, schemas_dir)
        shown = [k for k in keys if k in current]
        print(
            "\nSchemas changed since %s: %d (%d scored)"
            % (args.changed_since, len(keys), len(shown))
        )
        for key in shown:
            print_survivors(key, current[key])
        print()

    if args.update:
        data = build_baseline(current, min_score, args.include_library_composed)
        baseline_path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        print("wrote %s" % baseline_path)
        return 0
    if baseline is None:
        print("FAIL: no baseline at %s; create one with --update" % baseline_path)
        return 1
    if bool(baseline.get("include_library_composed")) != args.include_library_composed:
        print(
            "FAIL: the baseline was built with include_library_composed=%s; run with "
            "the same setting" % baseline.get("include_library_composed")
        )
        return 1

    judged = baseline.get("schemas", {})
    if scope is not None:
        # A scoped baselined schema that scored nothing (deleted, or its vectors
        # gone) is still in `judged`, so it fails as missing, as in the full sweep.
        judged = {k: v for k, v in judged.items() if k in scope}
    outcome = compare(judged, slimmed, min_score)
    for line in outcome["improvements"]:
        print("IMPROVED: %s" % line)
    for line in outcome["notes"]:
        print("NOTE: %s" % line)
    if outcome["improvements"]:
        print(
            "%d improvement(s) not yet locked in - refresh the baseline with "
            "--update" % len(outcome["improvements"])
        )
    for line in outcome["regressions"]:
        print("REGRESSION: %s" % line)
    if outcome["regressions"]:
        failed = sorted(set(r.split(":", 1)[0] for r in outcome["regressions"]))
        for key in failed:
            if key in current and not args.changed_since:
                print_survivors(key, current[key])
        print("FAIL: %d mutation-score regression(s)" % len(outcome["regressions"]))
        return 1
    print("PASS: no mutation-score regressions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
